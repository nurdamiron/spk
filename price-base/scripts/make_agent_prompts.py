def leads(keys, n=5):
    by = collections.defaultdict(list)
    for r in ROWS:
        if r["key"] in keys:
            by[r["key"]].append(r)
    out = []
    for k in keys:
        rs = by.get(k, [])
        sup = []
        seen = set()
        for r in rs:
            if r["sname"] not in seen:
                seen.add(r["sname"]); sup.append(f"{r['sname'][:34]} ({r['stype'][:14]}, {r['cls']})")
            if len(sup) >= n:
                break
        out.append((k, "; ".join(sup)))
    return dict(out)


def key_table(keys, extra_new=None):
    lv = leads(set(keys))
    L = ["| key | Позиция | Базовая ед. | Срок актуальности | Статус сейчас | Зацепки из прошлого сбора (поставщик, тип, класс) |", "|---|---|---|---|---|---|"]
    for k in keys:
        p, s = POS[k], SUM[k]
        L.append(f"| `{k}` | {p['name'][:80]} | {p['base'][:30]} | {'30 дн.' if p['vol'] else '90 дн.'} | {s['status'].split(':')[0]}; A={s['Asup']}, B={len(ROWS) and sum(1 for r in ROWS if r['key']==k and r['cls']=='B')}, C={s['nC']}, D={s['nD']} | {lv.get(k, '') or '—'} |")
    return "\n".join(L)


def compact_table(keys):
    L = ["| key | Позиция | Базовая ед. | Группа |", "|---|---|---|---|"]
    for k in keys:
        p = POS[k]
        L.append(f"| `{k}` | {p['name'][:80]} | {p['base'][:28]} | {p['group'][:30]} |")
    return "\n".join(L)


