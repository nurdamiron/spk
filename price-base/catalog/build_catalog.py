def main():
    st_path = os.path.join(ROOT, "data", "state.pkl")
    old = OrderedDict()
    if os.path.exists(st_path):
        ST = pickle.load(open(st_path, "rb"))
        for k, p in ST["POS"].items():
            old[k] = (k, p["group"], p["name"], p["base"], "", V if p["vol"] else N, 0)
    rows, seen = [], set()
    for it in list(old.values()) + items:
        if it[0] in seen:
            sys.exit(f"Дубликат ключа: {it[0]} (уже есть в каталоге или в прошлом сборе)")
        if it[1] not in G:
            sys.exit(f"Неизвестная группа у {it[0]}: {it[1]}")
        seen.add(it[0])
        rows.append(dict(key=it[0], group=it[1], agent=G[it[1]], name=it[2], base_unit=it[3], gost=it[4],
                         volatile=it[5], rare=it[6], source="Коктобе 138 (прошлый сбор)" if it[0] in old else "каталог"))
    out = os.path.join(HERE, "catalog_KZ.csv")
    with open(out, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()), delimiter=";")
        w.writeheader(); w.writerows(rows)
    try:
        from openpyxl import Workbook
        from openpyxl.styles import Font, PatternFill
        wb = Workbook(); ws = wb.active; ws.title = "Каталог"
        heads = ["Ключ", "Группа", "Агент", "Наименование", "Базовая ед.", "ГОСТ/СТ РК", "Волатильная (30 дн.)", "Редкая/дилерская", "Откуда"]
        ws.append(heads)
        for c in ws[1]:
            c.font = Font(bold=True, color="FFFFFF"); c.fill = PatternFill("solid", fgColor="1F3A5F")
        for r in rows:
            ws.append([r["key"], r["group"], r["agent"], r["name"], r["base_unit"], r["gost"], "да" if r["volatile"] else "нет",
                       "да" if r["rare"] else "", r["source"]])
        for col, wdt in zip("ABCDEFGHI", (20, 34, 16, 60, 14, 22, 10, 10, 24)):
            ws.column_dimensions[col].width = wdt
        ws.freeze_panes = "B2"; ws.auto_filter.ref = f"A1:I{len(rows) + 1}"
        s = wb.create_sheet("Сводка по группам"); s.append(["Группа", "Агент", "Позиций", "из них новых"])
        for gname, ag in G.items():
            s.append([gname, ag, sum(1 for r in rows if r["group"] == gname), sum(1 for r in rows if r["group"] == gname and r["key"] not in old)])
        s.append(["ИТОГО", "", len(rows), len(rows) - len(old)])
        wb.save(os.path.join(HERE, "catalog_KZ.xlsx"))
    except ImportError:
        pass
    print(f"catalog: {len(rows)} позиций ({len(old)} из прошлого сбора, {len(rows) - len(old)} новых) -> {out}")
    for gname, ag in G.items():
        print(f"  {ag:16} {sum(1 for r in rows if r['group'] == gname):4}  {gname}")


if __name__ == "__main__":
    main()
