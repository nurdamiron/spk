COMPS = {}   # key -> dict(parts=[...], missing=[...])
def p(key, val, cls, src): P[key] = (val, cls, src)
def _rows(k): return [x for x in RS.ROWS if x["key"] == k and x["sel"] and x["price"]]
def share_a(k):
    rs = _rows(k)
    return sum(1 for x in rs if x["cls"] == "A") / len(rs)
def C(*keys):
    return "A" if all(share_a(k) >= 0.5 for k in keys) else "L"
def sup(key):
    rs = _rows(key); names = []
    for x in rs:
        n = x["sup"].split(" (")[0].split(" —")[0].replace("Kaspi Объявления: ", "Kaspi: ")
        if n not in names: names.append(n)
    ex = [x["ex"] for x in rs]
    return f"{len(rs)} предл. (мин {min(ex):,.0f}–макс {max(ex):,.0f}; датир. 2026: {sum(1 for x in rs if x['cls']=='A')}): " + ", ".join(names[:4]) + ("…" if len(names) > 4 else "")
def simple(key, mk, label, extra=""):
    v = M(mk)
    p(key, v, C(mk), f"Медиана {v:,.0f} ₸ ({label}): {sup(mk)}. {extra}".strip())
def comp(key, parts, missing=(), note="", unit_note=""):
    """parts: (метка, норма на 1 ед. ВОР, ед. нормы, цена компонента, ед. цены, ключ источника или None)"""
    f = "=" + "+".join(f"{q}*{pr}" for _, q, _, pr, _, _ in parts)
    srck = [s for *_, s in parts if s]
    cls = "П" if missing else C(*srck)
    cost = sum(q * pr for _, q, _, pr, _, _ in parts)
    txt = f"Состав (норма × цена, ₸ без НДС): " + "; ".join(f"{l} {q:g}×{pr:,.0f}" for l, q, _, pr, _, _ in parts) + f" = {cost:,.0f}. "
    if note: txt += note + " "
    if missing: txt += "НЕ ВХОДИТ (нет цены КЗ 2026): " + "; ".join(missing) + "."
    p(key, f, cls, txt.strip())
    COMPS[key] = dict(parts=parts, missing=list(missing), cost=cost)

